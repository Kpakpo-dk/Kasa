  // Signature visual: a waveform that gradually resolves into
  // evenly-spaced kente-style colour blocks — voice becoming pattern.
  (function(){
    var el = document.getElementById('signature');
    var n = 40;
    var palette = ['#8A98BE','#C9982F','#A34632'];
    for (var i = 0; i < n; i++){
      var t = i / (n - 1); // 0 -> 1 across the row
      var bar = document.createElement('div');
      bar.className = 'bar';

      // left side: irregular waveform heights, muted colour
      // right side: settles into a steady woven rhythm, bolder colour
      var randomH = 18 + Math.random() * 70;
      var settledH = 55 + (i % 4) * 12;
      var h = randomH * (1 - t) + settledH * t;

      var muted = '#3A4770';
      var colorIndex = i % palette.length;
      var bold = palette[colorIndex];

      bar.style.height = h + 'px';
      bar.style.background = t < 0.15 ? muted : bold;
      bar.style.opacity = (0.5 + t * 0.5).toFixed(2);

      el.appendChild(bar);
    }
  })();
</script>

